<?php

declare(strict_types=1);

namespace Nabafzar\LogCenter\Console\Commands;

use Illuminate\Console\Command;
use Monolog\Level;
use Nabafzar\LogCenter\DTO\LogPayload;
use Nabafzar\LogCenter\Services\LogDispatcher;
use Throwable;

final class TestLogCommand extends Command
{
    protected $signature = 'logcenter:test-log
        {message? : Optional log message to send}
        {--level=error : Log level to use}
        {--channel=console : Log channel to include in the payload}
        {--driver= : Override the transport driver}
        {--formatter= : Override the formatter}';

    protected $description = 'Send a test log through Log Center.';

    public function __construct(
        private readonly LogDispatcher $dispatcher,
    ) {
        parent::__construct();
    }

    public function handle(): int
    {
        $level = $this->resolveLevel();

        if ($level === null) {
            return self::FAILURE;
        }

        $payload = new LogPayload(
            level: $level->getName(),
            message: $this->resolveMessage(),
            channel: $this->resolveChannel(),
            datetime: now()->toDateTimeImmutable(),
            environment: (string) config('app.env'),
            application: (string) config('app.name'),
            source: 'console',
            meta: [
                'command' => $this->getName(),
            ],
        );

        try {
            $result = $this->dispatcher->sendNow(
                payload: $payload,
                driverName: $this->resolveOption('driver'),
                formatterName: $this->resolveOption('formatter'),
            );
        } catch (Throwable $exception) {
            $this->error('Failed to send test log: ' . $exception->getMessage());

            return self::FAILURE;
        }

        if ($result->isFailure()) {
            $message = $result->errorMessage ?? 'Unknown transport failure.';

            $this->error(sprintf('Test log failed via %s: %s', $result->driver, $message));

            return self::FAILURE;
        }

        $this->info(sprintf('Test log sent via %s.', $result->driver));

        return self::SUCCESS;
    }

    private function resolveLevel(): ?Level
    {
        $level = $this->resolveOption('level') ?? 'error';

        try {
            return Level::fromName(strtoupper($level));
        } catch (Throwable) {
            $this->error(sprintf('Invalid log level: %s', $level));

            return null;
        }
    }

    private function resolveMessage(): string
    {
        $message = $this->argument('message');

        if (! is_string($message) || trim($message) === '') {
            return 'Test log generated by logcenter:test-log.';
        }

        return trim($message);
    }

    private function resolveChannel(): string
    {
        $channel = $this->resolveOption('channel');

        return $channel ?? 'console';
    }

    private function resolveOption(string $key): ?string
    {
        $value = $this->option($key);

        if (! is_string($value)) {
            return null;
        }

        $value = trim($value);

        return $value !== '' ? $value : null;
    }
}
